const assert = require('node:assert/strict');
const vm = require('node:vm');
const context = require('./dashboard_test_context.cjs')({});
const bins = (rows,end=24) => {
    context.rows=rows;context.end=end;
    return JSON.parse(JSON.stringify(vm.runInContext("powerPlotBins(rows,['power'],end)",context)));
};
const row=(minute,power)=>({h_of_day_frac:minute/60,power});
const close=(actual,expected)=>assert.ok(Math.abs(actual-expected)<1e-8,`${actual} != ${expected}`);
const samples=[row(0,0),row(1,10),row(4,null),row(10,20),row(11,null)];
const original=JSON.stringify(samples);
const result=bins(samples);
assert.equal(result.length,2);
close(result[0].power,7.5);
close(result[0].coverage.power,4/60);
close(result[1].power,20);
assert.equal(JSON.stringify(samples),original,'cached history is immutable');
assert.deepEqual(bins([row(0,null)]),[]);
assert.equal(bins([row(0,0)])[0].power,0,'real zero is retained');
assert.equal(bins([row(0,5),row(0,null)]).length,0,'last duplicate can invalidate an observation');
assert.equal(bins([row(0,10),row(30,20)]).length,2,'no invented bars in an outage');
const boundary=bins([row(9,10),row(12,null)]);
assert.equal(boundary.length,2,'interval crossing a bin edge is split');
close(boundary[0].coverage.power,1/60);close(boundary[1].coverage.power,2/60);
const partial=bins([row(10,5),row(11,15)],12/60);
assert.equal(partial.length,1);close(partial[0].bin_end,12/60);close(partial[0].power,10);
assert.equal(bins([row(12,10)],12/60).length,0,'never extrapolate beyond now');
const fullDay=bins(Array.from({length:1440},(_,minute)=>row(minute,minute%60)));
assert.equal(fullDay.length,144,'full day has at most 144 bins');
close(fullDay[0].power,4.5);close(fullDay.at(-1).power,54.5);
console.log('Ten-minute power bins passed: duration weights, zeros, nulls, outages, duplicates, boundaries, partial current bin and immutable source.');
